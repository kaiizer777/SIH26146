@pytest.mark.skipif(
    not (TRAILS_PATH.exists() and COMPOSITE_PATH.exists()),
    reason="Both evidence_trails.json and composite_risk_scores.json needed"
)
class TestCrossLayerConsistency:
    def test_composite_risk_gnn_matches_trail_risk_score(self):
        """XAI-D composite.risk_score must equal XAI-C trail.risk_score."""
        trails = _load_json(TRAILS_PATH)
        composites = _load_json(COMPOSITE_PATH)

        # Check up to 50 addresses that appear in both
        common = [a for a in list(composites.keys())[:200] if a in trails][:50]
        assert len(common) > 0, "No overlapping addresses between trails and composites"

        for addr in common:
            trail_rs = round(float(trails[addr]["risk_score"]), 4)
            comp_gnn = round(float(composites[addr]["risk_score"]), 4)
            assert abs(trail_rs - comp_gnn) < 0.0001, (
                f"risk_score mismatch for {addr[:20]}...: "
                f"trail.risk_score={trail_rs} vs composite.risk_score={comp_gnn}"
            )

    def test_all_composite_wallets_have_trail(self):
        """Every wallet in composite_risk_scores must have an evidence trail."""
        trails = _load_json(TRAILS_PATH)
        composites = _load_json(COMPOSITE_PATH)
        missing = [a for a in composites if a not in trails]
        assert len(missing) == 0, (
            f"{len(missing)} wallets in composites missing from evidence trails: "
            f"{missing[:5]}"
        )
