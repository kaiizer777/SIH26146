@pytest.mark.skipif(not SHAP_PATH.exists(), reason="shap_attributions.json not yet generated — run explain_autoencoder.py")
class TestSHAPAttributions:
    def test_file_is_nonempty(self):
        data = _load_json(SHAP_PATH)
        assert isinstance(data, dict), "shap_attributions.json must be a dict keyed by txid"
        assert len(data) > 0, "shap_attributions.json is empty"

    def test_structure_per_txid(self):
        """Each txid should have a list of 18 feature attribution dicts."""
        data = _load_json(SHAP_PATH)
        sample_txids = list(data.keys())[:10]
        for txid in sample_txids:
            waterfall = data[txid]
            assert isinstance(waterfall, list), f"Waterfall for {txid} must be a list"
            assert len(waterfall) == 18, (
                f"Expected 18 features for {txid}, got {len(waterfall)}"
            )
            for entry in waterfall:
                assert "feature" in entry, "Missing 'feature' key"
                assert "attribution" in entry, "Missing 'attribution' key"
                assert "value" in entry, "Missing 'value' key"
                assert isinstance(entry["attribution"], float), "'attribution' must be float"

    def test_sorted_by_magnitude(self):
        """Waterfall entries must be sorted by |attribution| descending."""
        data = _load_json(SHAP_PATH)
        sample_txids = list(data.keys())[:5]
        for txid in sample_txids:
            waterfall = data[txid]
            mags = [abs(e["attribution"]) for e in waterfall]
            assert mags == sorted(mags, reverse=True), (
                f"Waterfall for {txid} is not sorted by |attribution| descending"
            )

    def test_attribution_sum_nonzero(self):
        """At least some attributions must be nonzero — ensures SHAP actually ran."""
        data = _load_json(SHAP_PATH)
        sample_txids = list(data.keys())[:10]
        for txid in sample_txids:
            total_mag = sum(abs(e["attribution"]) for e in data[txid])
            assert total_mag > 0, f"All attributions are zero for {txid} — SHAP may have failed"

    def test_all_18_feature_names_present(self):
        """All 18 canonical feature names must appear in every waterfall."""
        from app.services.feature_extractor import FEATURE_NAMES
        data = _load_json(SHAP_PATH)
        sample_txids = list(data.keys())[:5]
        for txid in sample_txids:
            names_in_waterfall = {e["feature"] for e in data[txid]}
            for fname in FEATURE_NAMES:
                assert fname in names_in_waterfall, (
                    f"Feature '{fname}' missing from waterfall of {txid}"
                )


