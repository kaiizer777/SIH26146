def _load_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _skip_if_missing(path: Path, reason: str):
    """Return a pytest.mark.skipif decorator if path does not exist."""
    return pytest.mark.skipif(not path.exists(), reason=reason)


