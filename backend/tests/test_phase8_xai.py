@pytest.mark.skipif(not TRAILS_PATH.exists(), reason="evidence_trails.json not yet generated — run build_evidence_trails.py")
class TestEvidenceTrails:
    REQUIRED_KEYS = {
        "address", "cluster_id", "cluster_size", "anomaly_score",
        "anomaly_rank_percentile", "mixing_patterns", "chain_hops",
        "risk_score", "seed_wallet_proximity", "triggered_rules",
    }

    def test_file_is_nonempty(self):
        data = _load_json(TRAILS_PATH)
        assert isinstance(data, dict)
        assert len(data) > 0

    def test_required_fields_present(self):
        data = _load_json(TRAILS_PATH)
        sample = list(data.values())[:20]
        for trail in sample:
            missing = self.REQUIRED_KEYS - trail.keys()
            assert not missing, f"Missing fields in evidence trail: {missing}"

    def test_risk_score_bounded(self):
        data = _load_json(TRAILS_PATH)
        for addr, trail in data.items():
            rs = trail["risk_score"]
            assert 0.0 <= rs <= 1.0, f"risk_score {rs} out of range for {addr[:20]}..."

    def test_anomaly_percentile_bounded(self):
        data = _load_json(TRAILS_PATH)
        for addr, trail in data.items():
            pct = trail["anomaly_rank_percentile"]
            assert 0.0 <= pct <= 100.0, (
                f"anomaly_rank_percentile {pct} out of range for {addr[:20]}..."
            )

    def test_seed_wallets_have_rules(self):
        """Ransomwhere seed wallets in evidence trails must have RANSOMWHERE rule triggered."""
        data = _load_json(TRAILS_PATH)
        seed_file = _PROJECT_ROOT / "data" / "ransomwhere_seeds.json"
        if not seed_file.exists():
            pytest.skip("ransomwhere_seeds.json not found")
        with open(seed_file, "r", encoding="utf-8") as f:
            raw = json.load(f)
        records = raw.get("result", raw) if isinstance(raw, dict) else raw
        seed_addrs = {r["address"] for r in records if isinstance(r, dict) and "address" in r}

        seed_in_trails = [(addr, data[addr]) for addr in seed_addrs if addr in data]
        if not seed_in_trails:
            pytest.skip("No Ransomwhere seeds found in evidence trails")

        for addr, trail in seed_in_trails[:20]:
            rules_text = " ".join(trail["triggered_rules"])
            assert "RANSOMWHERE" in rules_text, (
                f"Seed wallet {addr[:20]}... missing RANSOMWHERE_SEED_ADDRESS rule. "
                f"Got: {trail['triggered_rules']}"
            )

    def test_triggered_rules_are_strings(self):
        data = _load_json(TRAILS_PATH)
        for addr, trail in list(data.items())[:20]:
            for rule in trail["triggered_rules"]:
                assert isinstance(rule, str), (
                    f"triggered_rule {rule!r} is not a string for {addr[:20]}..."
                )


