@pytest.mark.skipif(not GNN_PATH.exists(), reason="gnn_subgraphs.json not yet generated — run explain_graphsage.py")
class TestGNNSubgraphs:
    def test_file_is_nonempty(self):
        data = _load_json(GNN_PATH)
        assert isinstance(data, dict), "gnn_subgraphs.json must be a dict keyed by wallet address"
        assert len(data) > 0

    def test_top_k_count(self):
        data = _load_json(GNN_PATH)
        assert len(data) <= settings.gnn_explainer_top_k, (
            f"gnn_subgraphs.json has {len(data)} entries but top_k={settings.gnn_explainer_top_k}"
        )

    def test_structure_per_wallet(self):
        data = _load_json(GNN_PATH)
        sample = list(data.values())[:5]
        required_keys = {"address", "risk_score", "is_seed", "nodes", "edges", "feature_importance"}
        for wallet in sample:
            assert required_keys.issubset(wallet.keys()), (
                f"Missing keys in subgraph: {required_keys - wallet.keys()}"
            )
            assert isinstance(wallet["nodes"], list)
            assert isinstance(wallet["edges"], list)
            assert isinstance(wallet["feature_importance"], list)
            assert len(wallet["feature_importance"]) == 8, (
                f"Expected 8 feature importances, got {len(wallet['feature_importance'])}"
            )

    def test_target_wallet_in_own_subgraph(self):
        """The explained wallet must appear in its own subgraph nodes."""
        data = _load_json(GNN_PATH)
        sample = list(data.items())[:5]
        for addr, wallet in sample:
            node_addrs = {n["address"] for n in wallet["nodes"]}
            assert addr in node_addrs, (
                f"Target wallet {addr[:20]}... not in its own subgraph nodes"
            )

    def test_risk_score_bounded(self):
        data = _load_json(GNN_PATH)
        for addr, wallet in data.items():
            rs = wallet["risk_score"]
            assert 0.0 <= rs <= 1.0, f"risk_score {rs} out of bounds for {addr[:20]}..."


