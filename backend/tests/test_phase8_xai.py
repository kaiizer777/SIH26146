"""Phase 8 — XAI Layer Integration Tests.

Tests verify:
    - All four XAI output files exist and have correct structure.
    - SHAP attributions: all 18 features present, |attribution| sum > 0.
    - GNN subgraphs: nodes/edges/feature_importance fields non-empty.
    - Evidence trails: all required fields present, triggered_rules non-empty for flagged.
    - Composite scores: bounded [0, 1], internal consistency with evidence trails.
    - End-to-end consistency: composite.risk_gnn matches evidence_trail.risk_score.

These are integration tests — they skip gracefully if Docker services are down
(the XAI JSON files are pre-generated by the scripts, not regenerated here).
"""

